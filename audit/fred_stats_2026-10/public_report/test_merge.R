# End-to-end correction checks; temporary output is kept outside the repository.
args <- commandArgs(trailingOnly=TRUE)
P <- normalizePath(args[1]); input <- normalizePath(args[2])
source(file.path(P,"merge_fred_fixes.R"))
original <- readxl::read_xlsx(input,trim_ws=FALSE)
fixes <- .fred_read_csv(file.path(P,"fred_fixes.csv"))
apply <- function(x) apply_fred_fixes(x,file.path(P,"fred_fixes.csv"),file.path(P,"row_guard.csv"))
checks <- character()
expect <- function(ok,name) {if(!isTRUE(ok))stop(name);checks <<- c(checks,name)}
reject <- function(expr) inherits(tryCatch({force(expr);NULL},error=function(e)e),"error")
result <- apply(original)
expect(nrow(result$data)==2164L && identical(names(result$data),names(original)),"shape and columns preserved")
expect(identical(vapply(result$data,class,character(1)),vapply(original,class,character(1))),"column types preserved")
changed <- which(vapply(seq_along(original),function(j) sum(.fred_text(original[[j]])!=.fred_text(result$data[[j]])),integer(1))>0)
actual <- do.call(rbind,lapply(changed,function(j){i<-which(.fred_text(original[[j]])!=.fred_text(result$data[[j]]));data.frame(row=i,column=names(original)[j])}))
expected <- data.frame(row=match(.fred_key(fixes),.fred_key(original)),column=fixes$target_column)
expect(nrow(actual)==920L && setequal(paste(actual$row,actual$column),paste(expected$row,expected$column)),"exactly 920 intended physical cells changed")
expect(sum(result$changes$status=="applied")==920L,"all cell updates logged")
again <- apply(result$data)
expect(identical(again$data,result$data) && all(again$changes$status=="already_applied"),"second application is a no-op")
reordered <- apply(original[2164:1,])$data
expect(identical(reordered,result$data[2164:1,]),"reordered rows matched by identity, not row position")
bad <- original;bad$es_value_o[9] <- "CONFLICT";copy <- bad
expect(reject(apply(bad)) && identical(bad,copy),"changed old value rejected without mutation")
bad <- original;bad$description[9] <- "different outcome"
expect(reject(apply(bad)),"changed outcome identity rejected")
bad <- original;bad[2,c("entry_id","effect_id","fred_id")]<-bad[1,c("entry_id","effect_id","fred_id")]
expect(reject(apply(bad)),"duplicate record key rejected")
cache <- tempfile("fred-fix-test-");dir.create(cache)
altered <- file.path(cache,"tampered.csv");file.copy(file.path(P,"fred_fixes.csv"),altered);cat("\n",file=altered,append=TRUE)
expect(reject(apply_fred_fixes(original,altered,file.path(P,"row_guard.csv"))),"tampered download rejected")
output <- file.path(cache,"FReD_corrected.xlsx")
status <- system2(file.path(R.home("bin"),"Rscript"),shQuote(c(file.path(P,"merge_fred_fixes.R"),input,output)),stdout=file.path(cache,"cli.log"),stderr=file.path(cache,"cli.err"))
expect(status==0L && file.exists(output),"CLI writes a separate corrected workbook")
roundtrip <- readxl::read_xlsx(output,trim_ws=FALSE)
expect(all(vapply(names(original),function(k)identical(.fred_text(roundtrip[[k]]),.fred_text(result$data[[k]])),logical(1))),"XLSX round trip preserves corrected values")
expect(digest::digest(file=input,algo="sha256")==FRED_INPUT_SHA256,"original workbook remains byte-identical")
status <- system2(file.path(R.home("bin"),"Rscript"),shQuote(c(file.path(P,"merge_fred_fixes.R"),input,output)),stdout=FALSE,stderr=FALSE)
expect(status!=0L,"CLI refuses an existing output path")
# Check every primary correction and every attached inequality against the ledger.
confirmed <- .fred_read_csv(file.path(P,"confirmed_corrections.csv"))
idx <- match(.fred_key(confirmed),.fred_key(result$data))
expect(all(vapply(seq_len(nrow(confirmed)),function(i).fred_text(result$data[[confirmed$field[i]]][idx[i]])==.fred_text(confirmed$new_value[i]),logical(1))),"all 493 confirmed field replacements represented")
p <- which(confirmed$new_p_bound!="")
expect(all(vapply(p,function(i)startsWith(result$data[[paste0("pval_type_",substr(confirmed$field[i],nchar(confirmed$field[i]),nchar(confirmed$field[i]))) ]][idx[i]], confirmed$new_p_bound[i]),logical(1))),"all 115 p-value bounds retained")
receipt <- list(checks_passed=length(checks),checks=checks,confirmed_field_errors=493,physical_cell_updates=920,original_unchanged=TRUE,temporary_test_directory=cache,R=R.version.string,packages=vapply(c("readxl","writexl","digest"),function(p)as.character(packageVersion(p)),character(1)))
jsonlite::write_json(receipt,file.path(P,"r_validation.json"),pretty=TRUE,auto_unbox=TRUE)
cat(length(checks),"merge checks passed\n")
